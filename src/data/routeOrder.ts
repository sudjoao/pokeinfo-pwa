/**
 * Ordem em que os locais aparecem na história de cada jogo, para a aba "Rotas" listar do jeito
 * que o jogador avança (Route 1 antes de Celadon City) em vez de alfabeticamente.
 *
 * A PokéAPI não tem esse dado (`game_indices` é a numeração interna do mapa, não a ordem da
 * história). Escrito à mão a partir das walkthroughs da Bulbapedia e conferido com as listas do
 * repositório domtronn/nuzlocke.data (só referência: o repositório não tem licença, nada foi
 * copiado de lá). Quando um local é alcançável em mais de um momento, vale o primeiro em que dá
 * para encontrar um pokémon ali.
 *
 * Cada região é a união dos locais de todos os jogos dela: cada jogo usa só os que tem em
 * `routes.ts`/`routes-bdsp.ts` (ex.: RB, Yellow, FRLG e Let's Go compartilham `KANTO`). Um teste
 * (utils/__tests__/routes.spec.ts) garante que todo local com dado está em alguma seção do jogo.
 */

export interface RouteSection {
  /** Chave i18n do título da seção (`routes.section.*`), mostrado quando o jogo tem mais de uma. */
  key: string
  locations: readonly string[]
}

